function tableOut=SummarizeRevisionStudy(suite)
c=RevisionConfig(); folder=fullfile(c.outputRoot,suite); files=dir(fullfile(folder,'*_R*.mat')); rows={};
for k=1:numel(files)
    data=load(fullfile(files(k).folder,files(k).name),'job','result'); j=data.job; r=data.result;
    rows(end+1,:)={j.id,j.method,j.variant,j.repetition,j.cfg.numAgents,j.cfg.intervals,j.cfg.horizon,...
        r.success,r.successWithinBudget,r.timeWithinBudget,r.planningSeconds,r.cpuSeconds,r.outerIterations,r.solveCount,...
        r.initializationSeconds,r.guideSeconds,r.sfmAndTimingSeconds,r.corridorSeconds,r.assemblySeconds,r.solverSetupSeconds,...
        r.solveSeconds,r.endpointCorrectionSeconds,r.verificationSeconds,r.maxVariables,r.maxRows,r.maxNonzeros,...
        r.exactFinishCount,r.relocatedStatic,r.relocatedRelative,r.status,r.failureStage}; %#ok<AGROW>
end
labels={'Case','Method','Variant','Repeat','N','K','Tf','Accepted','AcceptedWithinBudget','TimeWithinBudget','Wall_s','CPU_s',...
    'OuterIterations','QPSolves','Initialization_s','Guide_s','SFM_Timing_s','Corridor_s','Assembly_s','SolverSetup_s',...
    'QPSolve_s','ControlCorrection_s','Verification_s','NumVariables','ConstraintRows','Nonzeros','ExactFinishSolves',...
    'StaticRelocations','RelativeRelocations','Status','FailureStage'};
tableOut=cell2table(rows,'VariableNames',labels);
if ~isempty(rows)
    temp=fullfile(folder,'summary.partial.csv'); writetable(tableOut,temp); movefile(temp,fullfile(folder,'summary.csv'),'f');
end
end
